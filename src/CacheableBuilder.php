<?php

namespace Daika7ana\LaravelModelCache;

use Illuminate\Contracts\Cache\Repository;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Support\Facades\Cache;
use Daika7ana\LaravelModelCache\Exceptions\UnfingerprintableEagerLoadException;

class CacheableBuilder extends Builder implements \Daika7ana\LaravelModelCache\Contracts\CacheableBuilderContract
{
    /**
     * The number of minutes to cache the query.
     *
     * @var int
     */
    protected $cacheMinutes;

    /**
     * Define a custom cache prefix for this model.
     * If not set, the global prefix from config('model-cache.cache_key_prefix') will be used.
     *
     * @var string
     */
    protected $cachePrefix;

    /**
     * Cached cache driver instance.
     *
     * @var \Illuminate\Contracts\Cache\Repository|null
     */
    protected $cacheDriver;

    /**
     * Per-model cache lock duration in seconds for stampede prevention.
     * Overrides config('model-cache.cache_lock_seconds') when set.
     *
     * @var int|null
     */
    protected $cacheLockSeconds;

    /**
     * Memoized eager-load constraint fingerprints, keyed by closure instance.
     * A WeakMap auto-evicts entries when a closure is freed (e.g. after
     * without()/withOnly()), so a reused object id can never return a stale
     * fingerprint.
     *
     * @var \WeakMap|null
     */
    protected $closureFingerprints;

    /**
     * Set when an eager-load constraint captures state that cannot be
     * fingerprinted (e.g. an object holding a closure). Such a query must not
     * use the cache at all — any key we build would be unsafe.
     *
     * @var bool
     */
    protected $eagerLoadUnfingerprintable = false;

    /**
     * Tables this query depends on beyond the root table (relations, pivots,
     * joins, subqueries, aggregates), collected for cache tagging.
     *
     * @var array<int, string>
     */
    protected $queryDependencyTables = [];

    /**
     * Set when a dependency's source builder cannot be recovered
     * (fromSub/joinSub/selectSub closures). Such a query must not use the cache.
     *
     * @var bool
     */
    protected $queryDependencyUncertain = false;

    /**
     * Tables and models discovered while resolving eager loads for the key.
     *
     * @var array<int, string>
     */
    protected $eagerDependencyTables = [];

    /**
     * @var array<class-string, \Illuminate\Database\Eloquent\Model>
     */
    protected $eagerDependencyModels = [];

    /**
     * Whether eager loads were already resolved for the current key.
     *
     * @var bool
     */
    protected $eagerDependenciesResolved = false;

    /**
     * Set when a column or binding cannot be fingerprinted losslessly.
     *
     * @var bool
     */
    protected $cacheKeyUnfingerprintable = false;

    /**
     * Set when the fetched result contains a morph type that is not registered
     * in the morph map. The result is returned but never written to the cache.
     *
     * @var bool
     */
    protected $resultUncacheable = false;

    /**
     * Set when the query resolves a MorphTo dependency. Without one, a loaded
     * result cannot contain an unmapped morph target worth scanning for.
     *
     * @var bool
     */
    protected $hasMorphDependency = false;

    /**
     * Select expressions generated by withAggregate() whose dependency tables
     * are already recorded. They contain a select but stay cacheable.
     *
     * @var \SplObjectStorage|null
     */
    protected $aggregateSelectExpressions;

    public function __construct($builder, $cacheMinutes = null, $cachePrefix = null, $cacheLockSeconds = null)
    {
        $this->cacheMinutes = $cacheMinutes;
        $this->cachePrefix = $cachePrefix;
        $this->cacheLockSeconds = $cacheLockSeconds;
        parent::__construct($builder);
    }

    /**
     * Touch all of the related models for the relationship.
     *
     * @param  null  $column
     * @return int|false
     */
    public function touch($column = null)
    {
        return $this->flushAfter(parent::touch($column), 'touch');
    }

    /**
     * Execute the query and get the first result from the cache.
     *
     * @param  array  $columns
     * @return \Illuminate\Database\Eloquent\Model|\stdClass|static|null
     */
    public function firstFromCache($columns = ['*'])
    {
        // Check if caching is globally disabled
        if (config('model-cache.enabled', true) === false) {
            return $this->clone()->take(1)->getWithoutCache($columns)->first();
        }

        // Check if caching is disabled for this query
        if (isset($this->cacheMinutes) && $this->cacheMinutes === 0) {
            return $this->clone()->take(1)->getWithoutCache($columns)->first();
        }

        $results = $this->clone()->take(1)->getFromCache($columns);

        return count($results) > 0 ? $results->first() : null;
    }

    /**
     * Execute the query and get the results from the cache.
     *
     * @param  array  $columns
     * @return \Illuminate\Database\Eloquent\Collection
     */
    public function getFromCache($columns = ['*']): Collection
    {
        if (config('model-cache.enabled', true) === false) {
            return $this->getWithoutCache($columns);
        }

        // Base-query afterQuery() callbacks mutate the result after the query
        // runs. Caching that mutated result would leak it into plain queries, so
        // such queries stay uncached.
        if ($this->hasAfterQueryCallbacks()) {
            return $this->getWithoutCache($columns);
        }

        $this->markUncertainForRawColumns($columns);

        $cacheKey = $this->getCacheKey($columns);
        $cacheTags = $this->getCacheTags();
        $minutes = $this->effectiveCacheMinutes();

        if ($this->shouldBypassCache($minutes)) {
            return $this->getWithoutCache($columns);
        }

        $cache = $this->getCacheDriver();

        try {
            return $this->rememberWithLock($cacheKey, $minutes * 60, function () use ($columns) {
                $result = $this->getWithoutCache($columns);

                // A partial morph map must not cache a result containing an
                // unmapped target: its key/tags/TTL are incomplete.
                if ($this->hasMorphDependency && $this->resultHasUnmappedMorphType($result)) {
                    $this->resultUncacheable = true;
                }

                return $result;
            }, $cacheTags);
        } catch (\Throwable $e) {
            if (config('model-cache.debug_mode', false)) {
                resolve(ModelCacheDebugger::class)->error("Cache read failed, bypassing cache: {$e->getMessage()}");
            }

            return $this->getWithoutCache($columns);
        }
    }

    /**
     * Set the cache duration.
     *
     * @param  int  $minutes
     * @return $this
     */
    public function remember($minutes)
    {
        // Don't set cache minutes if caching is globally disabled
        if (config('model-cache.enabled', true) === false) {
            return $this->withoutCache();
        }

        $this->cacheMinutes = $minutes;

        return $this;
    }

    /**
     * Disable caching for this query.
     *
     * @return $this
     */
    public function withoutCache()
    {
        $this->cacheMinutes = 0;

        return $this;
    }

    /**
     * Get a unique cache key for the complete query.
     *
     * @param  array  $columns
     * @param  bool  $withEagerLoads  Aggregates never eager-load, so they pass false.
     * @return string
     */
    public function getCacheKey($columns = ['*'], bool $withEagerLoads = true): string
    {
        // This is the prefix defined in our package config
        $configPrefix = $this->cachePrefix ?? config('model-cache.cache_key_prefix', 'model_cache_');

        // Fresh evaluation: a previous key computation must not leave a stale
        // uncacheable verdict behind for this builder.
        $this->eagerLoadUnfingerprintable = false;
        $this->cacheKeyUnfingerprintable = false;
        $this->hasMorphDependency = false;
        $this->eagerDependencyTables = [];
        $this->eagerDependencyModels = [];
        $this->eagerDependenciesResolved = false;

        // The base query itself may hide a subquery in a raw column/where/order.
        $this->markUncertainForRawSelect($this->toBase());

        $connection = $this->model->getConnection();

        // Create unique components for our key
        $keyComponents = [
            $configPrefix,
            get_class($this->model),
            $connection->getName(),
            $connection->getDatabaseName(),
            $this->model->getTable(),
            $this->toSql(),
            $this->bindingsFingerprint(),
            $this->columnsFingerprint($columns),
            config('model-cache.include_locale_in_key', false) ? app()->getLocale() : null,
        ];

        // Include eager loaded relationships, including any `with()` constraint
        // closures, so two differently-constrained eager loads cannot collide.
        if ($withEagerLoads && count($this->eagerLoad) > 0) {
            $keyComponents[] = 'with:' . $this->eagerLoadFingerprint();
        }

        $this->eagerDependenciesResolved = true;

        // serialize() (not implode) so a component can never forge the separator
        // and produce the same concatenation as a different component list.
        $uniqueKey = $this->hashIdentifier(serialize($keyComponents));

        // Add debug logging if enabled
        if (config('model-cache.debug_mode', false)) {
            resolve(ModelCacheDebugger::class)->debug("Generated cache key: {$uniqueKey} for query: {$this->toSql()} with " . count($this->getBindings()) . ' bindings and relations: ' . json_encode(array_keys($this->eagerLoad)));
        }

        // Return only the unique hash - Laravel will handle adding its own prefix
        return $uniqueKey;
    }

    /**
     * Flush the cache for this specific query.
     *
     * This method is called in two primary situations:
     * 1. Explicitly by the user: Model::where('condition', $value)->flushCache();
     * 2. Automatically after mass operations like update(), delete(), etc.
     *
     * The method attempts to clear the cache in three ways, in order of specificity:
     * 1. First, it tries to remove the specific cache key for this query
     * 2. If the cache driver supports tags, it tries to flush by model-specific tags
     * 3. As a fallback, it calls the model's flushModelCache() method
     *
     * @param  array  $columns
     * @return bool
     */
    public function flushQueryCache($columns = ['*']): bool
    {
        $connection = $this->model->getConnection();

        // Defer until the transaction commits so a rollback never invalidates cache.
        // The deferred callback must flush directly: the testing transactions manager
        // runs afterCommit() callbacks immediately while its wrapping transaction is
        // still open, so re-entering flushQueryCache() here would recurse forever.
        if ($connection->transactionLevel() > 0) {
            $connection->afterCommit(fn() => $this->performQueryCacheFlush($columns));

            return true;
        }

        return $this->performQueryCacheFlush($columns);
    }

    /**
     * Alias for flushQueryCache for backward compatibility with existing code.
     *
     * @param  array  $columns
     * @return bool
     */
    public function flushCache($columns = ['*'])
    {
        return $this->flushQueryCache($columns);
    }

    /**
     * Override the get method to automatically use cache.
     *
     * @param  array  $columns
     * @return \Illuminate\Database\Eloquent\Collection
     */
    public function get($columns = ['*'])
    {
        // Fast path: caching disabled globally
        if (config('model-cache.enabled', true) === false) {
            return parent::get($columns);
        }

        // Fast path: explicitly disabled for this query
        if (isset($this->cacheMinutes) && $this->cacheMinutes === 0) {
            return $this->getWithoutCache($columns);
        }

        return $this->getFromCache($columns);
    }

    /**
     * Paginate the given query with caching support.
     *
     * @param  int|null  $perPage
     * @param  array  $columns
     * @param  string  $pageName
     * @param  int|null  $page
     * @param  int|null  $total
     * @return \Illuminate\Contracts\Pagination\LengthAwarePaginator
     */
    public function paginate($perPage = null, $columns = ['*'], $pageName = 'page', $page = null, $total = null)
    {
        // Fast path: caching disabled globally
        if (config('model-cache.enabled', true) === false) {
            return parent::paginate($perPage, $columns, $pageName, $page, $total);
        }

        // Fast path: explicitly disabled for this query
        if (isset($this->cacheMinutes) && $this->cacheMinutes === 0) {
            return parent::paginate($perPage, $columns, $pageName, $page, $total);
        }

        return $this->paginateFromCache($perPage, $columns, $pageName, $page, $total);
    }

    /**
     * Paginate the given query with caching support.
     *
     * @param  int|null  $perPage
     * @param  array  $columns
     * @param  string  $pageName
     * @param  int|null  $page
     * @param  int|null  $total
     * @return \Illuminate\Contracts\Pagination\LengthAwarePaginator
     */
    public function paginateFromCache($perPage = null, $columns = ['*'], $pageName = 'page', $page = null, $total = null)
    {
        if (config('model-cache.enabled', true) === false) {
            return parent::paginate($perPage, $columns, $pageName, $page, $total);
        }

        // Fast path: explicitly disabled for this query
        if (isset($this->cacheMinutes) && $this->cacheMinutes === 0) {
            return parent::paginate($perPage, $columns, $pageName, $page, $total);
        }

        if ($this->hasAfterQueryCallbacks()) {
            return parent::paginate($perPage, $columns, $pageName, $page, $total);
        }

        $this->markUncertainForRawColumns($columns);

        $page = $page ?: \Illuminate\Pagination\Paginator::resolveCurrentPage($pageName);

        $perPage = $perPage ?: $this->model->getPerPage();

        $keyComponents = [
            'paginate',
            $perPage,
            $pageName,
            $page,
            $this->columnsFingerprint($columns),
            // The rendered paginator embeds its path, so the key must too.
            \Illuminate\Pagination\Paginator::resolveCurrentPath(),
        ];

        // A custom total produces a different paginator, so it must produce a different key
        if ($total !== null) {
            $keyComponents[] = $total;
        }

        $cacheKey = $this->getCacheKey($keyComponents);
        $cacheTags = $this->getCacheTags();
        $minutes = $this->effectiveCacheMinutes();

        if ($this->shouldBypassCache($minutes)) {
            return parent::paginate($perPage, $columns, $pageName, $page, $total);
        }

        $callback = function () use ($perPage, $columns, $pageName, $page, $total) {
            $result = parent::paginate($perPage, $columns, $pageName, $page, $total);

            if ($this->hasMorphDependency && $this->resultHasUnmappedMorphType($result)) {
                $this->resultUncacheable = true;
            }

            return $result;
        };

        try {
            return $this->rememberWithLock($cacheKey, $minutes * 60, $callback, $cacheTags);
        } catch (\Throwable $e) {
            if (config('model-cache.debug_mode', false)) {
                resolve(ModelCacheDebugger::class)->error("Cache read failed for paginate, bypassing cache: {$e->getMessage()}");
            }

            return $callback();
        }
    }

    /**
     * Add an aggregate subquery while recording the relation tables it reads.
     *
     * withCount()/withSum()/withAvg()/withMin()/withMax()/withExists() all route
     * through this method. Their subqueries are compiled into the parent SQL, so
     * the source builder is gone by tag time — record it here.
     *
     * @param  mixed  $relations
     * @param  mixed  $column
     * @param  string|null  $function
     * @return $this
     */
    public function withAggregate($relations, $column, $function = null)
    {
        foreach ((array) $relations as $key => $value) {
            $name = is_string($key) ? $key : $value;

            if (! is_string($name)) {
                $this->queryDependencyUncertain = true;

                continue;
            }

            $this->recordAggregateDependencies(preg_split('/\s+as\s+/i', $name)[0]);

            // withExists() compiles the constraint into an opaque exists(...)
            // selectRaw string, so any extra table it reads cannot be tagged.
            if ($function === 'exists' && $value instanceof \Closure) {
                $this->queryDependencyUncertain = true;
            }
        }

        $before = $this->expressionColumns();
        $result = parent::withAggregate($relations, $column, $function);

        $this->aggregateSelectExpressions ??= new \SplObjectStorage();

        foreach ($this->expressionColumns() as $expression) {
            if (! $before->contains($expression)) {
                $this->aggregateSelectExpressions->attach($expression);
            }
        }

        return $result;
    }

    /**
     * Add a subselect while recording the tables its source query reads.
     *
     * @param  mixed  $query
     * @param  string  $as
     * @return $this
     */
    public function selectSub($query, $as)
    {
        if ($query instanceof \Closure || is_string($query)) {
            // The query builder is only created inside the closure (or the raw
            // SQL is opaque), so its tables cannot be recovered here.
            $this->queryDependencyUncertain = true;
        } else {
            $this->queryDependencyTables = array_merge(
                $this->queryDependencyTables,
                $this->collectQueryDependencyTables($query),
            );
            $this->markUncertainForRawSelect($query);
        }

        $this->query->selectSub($query, $as);

        return $this;
    }

