    /**
     * Force a hard delete on a soft deleted model and flush cache.
     * This method overrides the forceDelete method present in the SoftDeletes trait.
     *
     * @return mixed
     */
    public function forceDelete()
    {
        // Check if the model uses SoftDeletes
        if (! method_exists($this->model, 'runSoftDelete')) {
            return $this->delete();
        }

        return $this->flushAfter(parent::forceDelete(), 'forceDelete');
    }

    /**
     * Restore soft deleted models and flush cache.
     * This method overrides the restore method present in the SoftDeletes trait.
     *
     * @return mixed
     */
    public function restore()
    {
        // Check if the model uses SoftDeletes
        if (! method_exists($this->model, 'runSoftDelete')) {
            return 0;
        }

        $result = parent::restore();

        // restore() goes through update(), which already flushed and marked this
        // model — only flush if it somehow didn't.
        if ($result && ! (method_exists($this->model, 'consumeCacheFlushMarker') && $this->model::consumeCacheFlushMarker($this->model))) {
            return $this->flushAfter($result, 'restore');
        }

        return $result;
    }

    /**
     * Snapshot the raw select expressions on the base query.
     *
     * @return \SplObjectStorage<int, \Illuminate\Database\Query\Expression>
     */
    protected function expressionColumns(): \SplObjectStorage
    {
        $expressions = new \SplObjectStorage();

        foreach ((array) ($this->query->columns ?? []) as $column) {
            if ($column instanceof \Illuminate\Database\Query\Expression) {
                $expressions->attach($column);
            }
        }

        return $expressions;
    }

    /**
     * Forget this query's specific cache key and flush its tags.
     *
     * @param  array  $columns
     * @return bool
     */
    protected function performQueryCacheFlush($columns = ['*']): bool
    {
        try {
            $cacheKey = $this->getCacheKey($columns);
            $cache = $this->getCacheDriver();
            // Storage entries live under the full tag namespace; the flush must
            // reset only this model's tags so other models stay cached.
            $cacheTags = $this->getCacheTags();
            $flushTags = $this->getModelFlushTags();
            $tagged = $cacheTags && $this->supportsTags($cache);

            if (config('model-cache.debug_mode', false)) {
                resolve(ModelCacheDebugger::class)->info("Flushing specific query cache: {$cacheKey}");
            }

            // Tagged stores scope the entry under the tag namespace, so the
            // specific-key forget must use the same tag set it was written with.
            $result = $tagged
                ? $cache->tags($cacheTags)->forget($cacheKey)
                : $cache->forget($cacheKey);

            if ($result && config('model-cache.debug_mode', false)) {
                resolve(ModelCacheDebugger::class)->debug("Successfully removed specific cache key: {$cacheKey}");
            }

            if ($tagged) {
                try {
                    $cache->tags($flushTags)->flush();
                    $result = true;
                    if (config('model-cache.debug_mode', false)) {
                        resolve(ModelCacheDebugger::class)->debug('Successfully flushed cache using tags for model: ' . get_class($this->model));
                    }
                } catch (\Throwable $e) {
                    if (config('model-cache.debug_mode', false)) {
                        resolve(ModelCacheDebugger::class)->debug("Could not flush by tags: {$e->getMessage()}");
                    }
                }
            }

            return $result;
        } catch (\Throwable $e) {
            resolve(ModelCacheDebugger::class)->error("Error flushing query cache: {$e->getMessage()}");

            return false;
        }
    }

    /**
     * Execute a cache read with optional stampede prevention locking.
     */
    protected function rememberWithLock(string $cacheKey, int $seconds, callable $callback, ?array $cacheTags = null)
    {
        $this->resultUncacheable = false;

        if (! config('model-cache.use_cache_locks', false)) {
            $driver = $this->getCacheDriver();
            $tagged = $cacheTags && $this->supportsTags($driver);

            try {
                $cached = $tagged
                    ? $driver->tags($cacheTags)->get($cacheKey)
                    : $driver->get($cacheKey);

                if ($cached !== null) {
                    resolve(ModelCacheDebugger::class)->debug("Cache hit for key: {$cacheKey}");

                    return $cached;
                }
            } catch (\Throwable $e) {
                // Cache read failure is fail-open; execute the query below.
            }

            resolve(ModelCacheDebugger::class)->debug("Cache miss, executing query for key: {$cacheKey}");
            $result = $callback();

            if (! $this->resultUncacheable) {
                if ($tagged) {
                    $driver->tags($cacheTags)->put($cacheKey, $result, $seconds);
                } else {
                    $driver->put($cacheKey, $result, $seconds);
                }
            }

            return $result;
        }

        $cache = $this->getCacheDriver();
        $lockKey = "stampede:{$cacheKey}";
        $lockDuration = $this->cacheLockSeconds ?? config('model-cache.cache_lock_seconds', 5);

        // Try to get existing cached value first
        try {
            if ($cacheTags && $this->supportsTags($cache)) {
                $cached = $cache->tags($cacheTags)->get($cacheKey);
            } else {
                $cached = $cache->get($cacheKey);
            }

            if ($cached !== null) {
                resolve(ModelCacheDebugger::class)->debug("Cache hit for key: {$cacheKey}");

                return $cached;
            }
        } catch (\Throwable $e) {
            // Cache miss or error — proceed to lock
        }

        // Acquire lock to prevent stampede
        $lock = $cache->lock($lockKey, $lockDuration);

        if ($lock->get()) {
            resolve(ModelCacheDebugger::class)->debug("Cache miss, executing query for key: {$cacheKey}");

            try {
                $result = $callback();

                if (! $this->resultUncacheable) {
                    if ($cacheTags && $this->supportsTags($cache)) {
                        $cache->tags($cacheTags)->put($cacheKey, $result, $seconds);
                    } else {
                        $cache->put($cacheKey, $result, $seconds);
                    }
                }

                return $result;
            } finally {
                $lock->release();
            }
        }

        // Another request is computing — poll for the result until the lock
        // duration elapses, then fall back to executing the query directly.
        $deadline = microtime(true) + $lockDuration;

        while (microtime(true) < $deadline) {
            usleep(50000); // 50ms

            try {
                $cached = $cacheTags && $this->supportsTags($cache)
                    ? $cache->tags($cacheTags)->get($cacheKey)
                    : $cache->get($cacheKey);
            } catch (\Throwable $e) {
                // If the re-read fails, just execute the query directly
                resolve(ModelCacheDebugger::class)->debug("Cache miss, executing query for key: {$cacheKey}");

                return $callback();
            }

            if ($cached !== null) {
                resolve(ModelCacheDebugger::class)->debug("Cache hit for key: {$cacheKey}");

                return $cached;
            }
        }

        // The lock holder is still computing past the lock duration — execute
        // the query directly instead of returning null to a caller expecting a Collection.
        resolve(ModelCacheDebugger::class)->debug("Cache miss, executing query for key: {$cacheKey}");

        return $callback();
    }

    /**
     * Execute an aggregate query with caching support.
     *
     * @param  string  $method  The aggregate method name (count, sum, min, max, avg)
     * @param  string  $column  The column to aggregate
     * @return mixed
     */
    protected function aggregateFromCache(string $method, string $column)
    {
        if (config('model-cache.enabled', true) === false) {
            return parent::{$method}($column);
        }

        // Explicit cache bypass for this query
        if (isset($this->cacheMinutes) && $this->cacheMinutes === 0) {
            return parent::{$method}($column);
        }

        $cacheKey = $this->getCacheKey([$method, $column], false);
        $cacheTags = $this->getCacheTags();
        $minutes = $this->effectiveCacheMinutes();

        if ($this->shouldBypassCache($minutes)) {
            return parent::{$method}($column);
        }

        $callback = fn() => parent::{$method}($column);

        try {
            return $this->rememberWithLock($cacheKey, $minutes * 60, $callback, $cacheTags);
        } catch (\Throwable $e) {
            if (config('model-cache.debug_mode', false)) {
                resolve(ModelCacheDebugger::class)->error("Cache read failed for {$method}, bypassing cache: {$e->getMessage()}");
            }

            return $callback();
        }
    }

    /**
     * Check if the cache driver supports tags.
     *
     * @param  \Illuminate\Contracts\Cache\Repository  $cache
     * @return bool
     */
    protected function supportsTags($cache)
    {
        try {
            return method_exists($cache, 'supportsTags') && $cache->supportsTags();
        } catch (\Throwable $e) {
            return false;
        }
    }

    /**
     * Flush the cache after a mass operation when it affected rows.
     *
     * @param  mixed  $result
     * @return mixed
     */
    protected function flushAfter($result, string $operation)
    {
        if ($result) {
            if (config('model-cache.debug_mode', false)) {
                resolve(ModelCacheDebugger::class)->info("Flushing cache after `{$operation}` operation for model: " . get_class($this->model));
            }

            $this->flushModelOrQueryCache($operation);
        }

        return $result;
    }

    /**
     * Flush model cache when available, otherwise flush query cache.
     */
    protected function flushModelOrQueryCache(?string $operation = null): void
    {
        $flush = function () use ($operation) {
            if (method_exists($this->model, 'flushModelCache')) {
                $this->model->flushModelCache($operation);

                // Instance operations (delete/forceDelete) run through this builder first
                // and then fire the `deleted` event; mark the instance so the event handler
                // skips its redundant flush.
                if (method_exists($this->model, 'markCacheFlushed')) {
                    $this->model->markCacheFlushed($this->model);
                }
            } else {
                $this->flushQueryCache();
            }
        };

        $connection = $this->model->getConnection();

        if ($connection->transactionLevel() > 0) {
            $connection->afterCommit($flush);
        } else {
            $flush();
        }
    }

    /**
     * Hash a value for cache identifiers.
     *
     * Uses configured hashing algorithm (default: xxh128).
     */
    protected function hashIdentifier(string $value): string
    {
        $algorithm = strtolower((string) config('model-cache.hash_algorithm', 'xxh128'));

        try {
            return hash($algorithm, $value);
        } catch (\ValueError $e) {
            // Keep the exception type consistent with the provider's boot-time validation
            throw new \InvalidArgumentException(
                "Invalid model-cache.hash_algorithm '{$algorithm}'. Available algorithms: " . implode(', ', array_slice(hash_algos(), 0, 10)) . '...',
                previous: $e,
            );
        }
    }

    /**
     * Fingerprint the query bindings losslessly.
     *
     * Scalar bindings are serialized as one array: exact, binary-safe, and much
     * faster than encoding every value for large whereIn() lists. Arrays,
     * resources and closures keep the per-value path that flags them unsafe.
     */
    protected function bindingsFingerprint($bindings = null): string
    {
        $bindings = $bindings ?? $this->getBindings();

        foreach ($bindings as $binding) {
            if (is_array($binding) || is_resource($binding) || $binding instanceof \Closure) {
                return $this->losslessFingerprint($bindings);
            }
        }

        try {
            return serialize($bindings);
        } catch (\Throwable $e) {
            return $this->losslessFingerprint($bindings);
        }
    }

    /**
     * Fingerprint the selected columns losslessly.
     *
     * @param  mixed  $columns
     */
    protected function columnsFingerprint($columns): string
    {
        return $this->losslessFingerprint($columns);
    }

    /**
     * Fingerprint a value without relying on json_encode(), which collapses
     * Expression objects to {} and resources to false. serialize() preserves
     * binary strings, key types and private object state exactly.
     *
     * @param  mixed  $value
     */
    protected function losslessFingerprint($value, int $depth = 0): string
    {
        if ($depth > 8) {
            $this->cacheKeyUnfingerprintable = true;

            return 'depth';
        }

        if (is_resource($value)) {
            $this->cacheKeyUnfingerprintable = true;

            return 'resource';
        }

        if ($value instanceof \Closure) {
            $this->cacheKeyUnfingerprintable = true;

            return 'closure';
        }

        if (is_array($value)) {
            $encoded = [];

            foreach ($value as $key => $item) {
                $encoded[$key] = $this->losslessFingerprint($item, $depth + 1);
            }

            return 'arr:' . serialize($encoded);
        }

        if (is_string($value)) {
            return 'str:' . serialize($value);
        }

        if ($value instanceof \Illuminate\Database\Query\Expression) {
            try {
                return 'expr:' . serialize((string) $value->getValue($this->getQuery()->getGrammar()));
            } catch (\Throwable $e) {
                $this->cacheKeyUnfingerprintable = true;

                return 'expr';
            }
        }

        if (is_object($value)) {
            try {
                return 'ser:' . serialize($value);
            } catch (\Throwable $e) {
                if ($value instanceof \Stringable) {
                    return 'str:' . serialize((string) $value);
                }

                $this->cacheKeyUnfingerprintable = true;

                return 'object';
            }
        }

        if (is_int($value) || is_float($value) || is_bool($value) || $value === null) {
            return gettype($value) . ':' . var_export($value, true);
        }

        $this->cacheKeyUnfingerprintable = true;

        return gettype($value);
    }

    /**
     * Whether this query's result must not be cached. A zero TTL for this
     * query or an eager-loaded dependency also bypasses the cache.
     */
    protected function shouldBypassCache(?int $minutes = null): bool
    {
        if ($minutes !== 0
            && ! $this->eagerLoadUnfingerprintable
            && ! $this->queryDependencyUncertain
            && ! $this->cacheKeyUnfingerprintable) {
            return false;
        }

        if (config('model-cache.debug_mode', false)) {
            resolve(ModelCacheDebugger::class)->debug('Bypassing cache for this query.');
        }

        return true;
    }

    /**
     * Whether the builder has any afterQuery() callbacks.
     */
    protected function hasAfterQueryCallbacks(): bool
    {
        return $this->builderHasAfterQueryCallbacks($this);
    }

    /**
     * Whether a builder (root or relation query) has afterQuery() callbacks.
     * Reflection is used because the property is protected on a parent class.
     */
    protected function builderHasAfterQueryCallbacks($builder): bool
    {
        if (! is_object($builder) || ! property_exists($builder, 'afterQueryCallbacks')) {
            return false;
        }

        try {
            $property = new \ReflectionProperty($builder, 'afterQueryCallbacks');
            $property->setAccessible(true);

            return ! empty($property->getValue($builder));
        } catch (\Throwable $e) {
            return false;
        }
    }

    /**
     * Effective TTL for this query. The cached root result embeds eager-loaded
     * data, so the shortest TTL across the root and every eager-loaded model
     * wins. A related model's $cacheMinutes = 0 disables caching for the root.
     */
    protected function effectiveCacheMinutes(): int
    {
        $minutes = (int) ($this->cacheMinutes ?: config('model-cache.cache_duration', 60));

        foreach ($this->eagerDependencyModels as $model) {
            $relatedMinutes = $this->modelCacheMinutes($model)
                ?? (int) config('model-cache.cache_duration', 60);

            if ($relatedMinutes === 0) {
                return 0;
            }

            $minutes = min($minutes, $relatedMinutes);
        }

        return $minutes;
    }

    /**
     * Read a model's $cacheMinutes property without requiring it to be public.
     */
    protected function modelCacheMinutes($model): ?int
    {
        if (! property_exists($model, 'cacheMinutes')) {
            return null;
        }

        try {
            $property = new \ReflectionProperty($model, 'cacheMinutes');
            $property->setAccessible(true);

            if (! $property->isInitialized($model)) {
                return null;
            }

            $value = $property->getValue($model);

            return is_numeric($value) ? (int) $value : null;
        } catch (\Throwable $e) {
            return null;
        }
    }

    /**
     * Build a stable fingerprint for the eager-load constraints on this query.
     *
     * Laravel wraps every `with()` constraint in a combineConstraints() closure,
     * so we walk captured variables to reach the user's closure. When a capture
     * cannot be fingerprinted, the constraint is resolved against a fresh relation
     * and the resulting relation state is fingerprinted instead. Only if that also
     * fails does the query fall back to bypassing the cache.
     *
     * Constraint closures run on every key/tag computation, including cache hits,
     * so they must be side-effect free and should not query.
     */
    protected function eagerLoadFingerprint(): string
    {
        $fingerprints = $this->fingerprintEagerLoads($this);

        // Eager-load insertion order must not change the key.
        ksort($fingerprints);

        return serialize($fingerprints);
    }

    /**
     * Fingerprint a builder's eager loads, grouped by root relation so a dotted
     * name shares one resolution with its root.
     *
     * @return array<string, string>
     */
    protected function fingerprintEagerLoads($builder, int $depth = 0): array
    {
        if ($depth > 6) {
            $this->eagerLoadUnfingerprintable = true;

            return [];
        }

        // afterQuery() callbacks (including chaperone()) mutate the relation
        // result after it is loaded; caching that result would leak it.
        if ($this->builderHasAfterQueryCallbacks($builder)) {
            $this->eagerLoadUnfingerprintable = true;
        }

        $groups = [];

        foreach ($builder->getEagerLoads() as $name => $constraint) {
            $root = str_contains($name, '.') ? strstr($name, '.', true) : $name;
            $groups[$root][$name] = $constraint;
        }

        $fingerprints = [];

        foreach ($groups as $root => $entries) {
            // Resolve every group, not only the ones with an unfingerprintable
            // closure: related global scopes, $with, pivot props and nested
            // constraints only appear in the resolved relation state.
            $fingerprints[$root] = 'resolved:' . $this->resolveEagerLoadGroup($builder, $root, $entries, $depth);
        }

        return $fingerprints;
    }

    /**
     * Resolve an un-fingerprintable eager-load group against a fresh relation and
     * fingerprint the resulting relation state. Falls back to an uncacheable
     * verdict if the relation cannot be built or the constraint throws.
     *
     * Constraint closures run on every key/tag computation, including cache hits,
     * so they must be side-effect free and should not query.
     *
     * @param  array<string, \Closure>  $entries
     */
    protected function resolveEagerLoadGroup($builder, string $root, array $entries, int $depth): string
    {
        try {
            $relation = $builder->getRelation($root);

            if ($this->builderHasAfterQueryCallbacks($relation->getQuery())) {
                $this->eagerLoadUnfingerprintable = true;
            }

            foreach ($entries as $name => $constraint) {
                // Dotted entries are applied to nested relations by getRelation();
                // only the root's own constraint runs here.
                if ($constraint instanceof \Closure && ! str_contains($name, '.')) {
                    $constraint($relation);
                }
            }

            // A constraint may call afterQuery() on the relation query. Check
            // again after the constraint runs, not only before it.
            if ($this->builderHasAfterQueryCallbacks($relation->getQuery())) {
                $this->eagerLoadUnfingerprintable = true;
            }

            if ($relation instanceof \Illuminate\Database\Eloquent\Relations\MorphTo) {
                $this->hasMorphDependency = true;

                return $this->morphToStateFingerprint($relation, $depth + 1);
            }

            $this->recordEagerDependency($relation);

            return $this->relationStateFingerprint($relation, $depth + 1);
        } catch (\Throwable $e) {
            $this->eagerLoadUnfingerprintable = true;

            return 'unresolvable';
        }
    }

    /**
     * Fingerprint a MorphTo by resolving every mapped morph type and hashing
     * that target's scoped query state. Without a morph map there is no complete
     * set of possible targets, so the query stays uncacheable.
     */
    protected function morphToStateFingerprint($relation, int $depth): string
    {
        $types = $this->morphTypesForFingerprint();

        if ($types === null) {
            $this->eagerLoadUnfingerprintable = true;

            return 'morphTo';
        }

        sort($types);
        // Nested eager loads on a MorphTo query belong to the concrete target,
        // not to the parent-model query, so hash them per target below.
        $parts = ['morphTo', $this->relationStateFingerprint($relation, $depth, true)];

        foreach ($types as $type) {
            $target = $this->morphTargetFingerprint($relation, $type, $depth);

            if ($target === null) {
                $this->eagerLoadUnfingerprintable = true;

                return 'morphTo';
            }

            $parts[] = 'type:' . $type . '=' . $target;
        }

        return serialize($parts);
    }

    /**
     * All types registered in the morph map. Without a map we cannot enumerate
     * every possible target safely, so morphTo eager loads bypass the cache.
     *
     * @return array<int, string>|null
     */
    protected function morphTypesForFingerprint(): ?array
    {
        $map = \Illuminate\Database\Eloquent\Relations\Relation::morphMap();

        if ($map === []) {
            return null;
        }

        $types = array_values(array_filter(
            array_map('strval', array_keys($map)),
            fn($type) => $type !== '',
        ));

        return $types === [] ? null : $types;
    }

    /**
     * Build the resolved query for one morph target, mirroring Laravel's
     * getResultsByType() before scopes and the whereIn are applied.
     *
     * @return array{0: \Illuminate\Database\Eloquent\Builder, 1: \Illuminate\Database\Eloquent\Model}
     */
    protected function morphTargetQuery($relation, string $type): array
    {
        $target = $relation->createModelByType($type);
        $class = get_class($target);

        $query = $target->newQuery();
        $this->replayMorphMacros($relation, $query);
        $query->mergeConstraintsFrom($relation->getQuery());

        $relationEagerLoads = $relation->getQuery()->getEagerLoads();
        if ($relationEagerLoads !== []) {
            $query->with($relationEagerLoads);
        }

        $eagerLoads = $this->morphableValue($relation, 'morphableEagerLoads', $class);
        if ($eagerLoads !== null && (array) $eagerLoads !== []) {
            $query->with((array) $eagerLoads);
        }

        $eagerLoadCounts = $this->morphableValue($relation, 'morphableEagerLoadCounts', $class);
        if ($eagerLoadCounts !== null && (array) $eagerLoadCounts !== []) {
            $query->withCount((array) $eagerLoadCounts);
        }

        $constraint = $this->morphableValue($relation, 'morphableConstraints', $class);
        if (is_callable($constraint)) {
            $constraint($query);
        }

        return [$query, $target];
    }

    /**
     * Fingerprint one morph target's resolved query: global scopes, table,
     * database, merged relation constraints, macros, morphWith/withCount, and
     * nested eager loads.
     */
    protected function morphTargetFingerprint($relation, string $type, int $depth): ?string
    {
        try {
            [$query, $target] = $this->morphTargetQuery($relation, $type);
            $class = get_class($target);

            // Global scopes can add eager loads or afterQuery() callbacks, so
            // fingerprint the scoped builder, not the raw newQuery() builder.
            $scoped = $query->applyScopes();

            if ($this->builderHasAfterQueryCallbacks($scoped)
                || $this->builderHasAfterQueryCallbacks($scoped->getQuery())) {
                return null;
            }

            $this->mergeDependencyTablesFrom($scoped);

            $base = $scoped->getQuery();

            // A non-CacheableBuilder target cannot record withCount()/selectSub
            // dependencies. Any raw select expression may hide one, so bypass.
            if (! $query instanceof self) {
                $this->markUncertainForRawSelect($scoped);

                if ($this->queryDependencyUncertain) {
                    return null;
                }
            }

            $this->queryDependencyTables = array_merge(
                $this->queryDependencyTables,
                $this->collectQueryDependencyTables($base, $depth + 1),
            );

            $parts = [
                'class:' . $class,
                'connection:' . ($target->getConnectionName() ?? ''),
                'database:' . $target->getConnection()->getDatabaseName(),
                'table:' . $target->getTable(),
                'sql:' . $base->toSql(),
                'bindings:' . $this->bindingsFingerprint($base->getBindings()),
            ];

            if (count($scoped->getEagerLoads()) > 0) {
                $nested = $this->fingerprintEagerLoads($scoped, $depth + 1);
                ksort($nested);
                $parts[] = 'with:' . serialize($nested);
            }

            $this->recordMorphTargetDependency($target);

            return serialize($parts);
        } catch (\Throwable $e) {
            return null;
        }
    }

    /**
     * Replay MorphTo macro-buffer calls on the concrete target query. This
     * mirrors Laravel's own replayMacros() step before constraints are merged.
     */
    protected function replayMorphMacros($relation, $query): void
    {
        if (! property_exists($relation, 'macroBuffer')) {
            return;
        }

        try {
            $reflection = new \ReflectionProperty($relation, 'macroBuffer');
            $reflection->setAccessible(true);
            $macros = $reflection->getValue($relation);
        } catch (\Throwable $e) {
            return;
        }

        foreach ((array) $macros as $macro) {
            if (is_array($macro) && isset($macro['method']) && is_string($macro['method'])) {
                $query->{$macro['method']}(...($macro['parameters'] ?? []));
            }
        }
    }

    /**
     * Detect a fetched morphTo target whose type is not registered in the morph
     * map. Such a result is returned to the caller but must never be cached,
     * because its key/tags/TTL did not include that target.
     */
    protected function resultHasUnmappedMorphType($result): bool
    {
        if (method_exists($result, 'getCollection')) {
            $result = $result->getCollection();
        }

        $visited = new \SplObjectStorage();

        if ($result instanceof \Illuminate\Database\Eloquent\Model) {
            return $this->modelHasUnmappedMorphType($result, $visited);
        }

        if (is_iterable($result)) {
            foreach ($result as $model) {
                if ($model instanceof \Illuminate\Database\Eloquent\Model
                    && $this->modelHasUnmappedMorphType($model, $visited)) {
                    return true;
                }
            }
        }

        return false;
    }

    /**
     * Recursively check loaded relations for an unmapped morph type.
     */
    protected function modelHasUnmappedMorphType($model, \SplObjectStorage $visited): bool
    {
        if ($visited->contains($model)) {
            return false;
        }

        $visited->attach($model);

        foreach ($model->getRelations() as $name => $related) {
            // Pivot data is stored as a relation but is not a relationship method.
            if ($name === 'pivot' || ! method_exists($model, $name)) {
                continue;
            }

            try {
                $relation = $model->{$name}();
            } catch (\Throwable $e) {
                return true;
            }

            // Check the type even when the relation value is null: an unmapped
            // type still has no tag/TTL entry, so its future target could not
            // invalidate this snapshot.
            if ($relation instanceof \Illuminate\Database\Eloquent\Relations\MorphTo) {
                $type = $model->getAttribute($relation->getMorphType());

                if ($type && ! $this->morphTypeIsMapped((string) $type)) {
                    return true;
                }
            }

            if ($related instanceof \Illuminate\Database\Eloquent\Model) {
                if ($this->modelHasUnmappedMorphType($related, $visited)) {
                    return true;
                }

                continue;
            }

            if (! $related instanceof \Illuminate\Support\Collection) {
                continue;
            }

            foreach ($related as $item) {
                if ($item instanceof \Illuminate\Database\Eloquent\Model
                    && $this->modelHasUnmappedMorphType($item, $visited)) {
                    return true;
                }
            }
        }

        return false;
    }

    /**
     * Whether a stored morph type is covered by the morph map.
     */
    protected function morphTypeIsMapped(string $type): bool
    {
        $map = \Illuminate\Database\Eloquent\Relations\Relation::morphMap();

        return array_key_exists($type, $map) || in_array($type, $map, true);
    }

    /**
     * Read one per-class morph option without requiring a getter.
     */
    protected function morphableValue($relation, string $property, string $class): mixed
    {
        if (! property_exists($relation, $property)) {
            return null;
        }

        try {
            $reflection = new \ReflectionProperty($relation, $property);
            $reflection->setAccessible(true);
            $values = $reflection->getValue($relation);

            return is_array($values) ? ($values[$class] ?? null) : null;
        } catch (\Throwable $e) {
            return null;
        }
    }

    /**
     * Record a concrete morph target's table and model for tags/TTL.
     */
    protected function recordMorphTargetDependency($target): void
    {
        $this->eagerDependencyTables[] = $target->getTable();
        $this->eagerDependencyModels[get_class($target)] = $target;
    }

    /**
     * Merge dependency state recorded by a nested CacheableBuilder (for example
     * a withCount() added inside a morph target or eager-load constraint).
     */
    protected function mergeDependencyTablesFrom($query): void
    {
        if ($query instanceof self) {
            $this->queryDependencyTables = array_merge(
                $this->queryDependencyTables,
                $query->queryDependencyTables,
            );
            $this->eagerDependencyTables = array_merge(
                $this->eagerDependencyTables,
                $query->eagerDependencyTables,
            );
            $this->eagerDependencyModels = array_merge(
                $this->eagerDependencyModels,
                $query->eagerDependencyModels,
            );
            $this->queryDependencyUncertain = $this->queryDependencyUncertain || $query->queryDependencyUncertain;
        }
    }

    /**
     * A plain Eloquent builder cannot record withCount()/selectSub dependencies.
     * Any raw select expression may hide one, so mark the query uncacheable.
     */
    protected function markUncertainForRawSelect($builder): void
    {
        $query = $builder instanceof \Illuminate\Database\Eloquent\Builder
            ? $builder->getQuery()
            : $builder;

        if (! $query instanceof \Illuminate\Database\Query\Builder) {
            return;
        }

        $tracked = $this->aggregateSelectExpressions;

        $this->markUncertainInQuery($query, $tracked, 0);
    }

    /**
     * Walk a query and every subquery it embeds. Raw SQL anywhere — columns,
     * wheres, havings, join ON, orders, groups, unions — may read a table that
     * cannot be tagged, so such queries must bypass the cache.
     *
     * @param  mixed  $query
     * @param  mixed  $tracked
     */
    protected function markUncertainInQuery($query, $tracked, int $depth): void
    {
        if ($depth > 6 || $this->queryDependencyUncertain) {
            return;
        }

        foreach ((array) ($query->columns ?? []) as $column) {
            if ($column instanceof \Illuminate\Database\Query\Expression
                && $tracked !== null
                && $tracked->contains($column)) {
                continue;
            }

            if ($this->rawSqlContainsSelect($column, $query)) {
                $this->queryDependencyUncertain = true;

                return;
            }
        }

        $this->markUncertainInClauses((array) ($query->wheres ?? []), $query, $tracked, $depth);

        if ($this->queryDependencyUncertain) {
            return;
        }

        $this->markUncertainInClauses((array) ($query->havings ?? []), $query, $tracked, $depth);

        if ($this->queryDependencyUncertain) {
            return;
        }

        foreach ((array) ($query->orders ?? []) as $order) {
            if ($this->rawSqlContainsSelect($order['column'] ?? null, $query)) {
                $this->queryDependencyUncertain = true;

                return;
            }
        }

        foreach ((array) ($query->groups ?? []) as $group) {
            if ($this->rawSqlContainsSelect($group, $query)) {
                $this->queryDependencyUncertain = true;

                return;
            }
        }

        foreach ((array) ($query->joins ?? []) as $join) {
            $wheres = is_array($join) ? ($join['wheres'] ?? []) : ($join->wheres ?? []);

            $this->markUncertainInClauses((array) $wheres, $query, $tracked, $depth);

            if ($this->queryDependencyUncertain) {
                return;
            }
        }

        foreach ((array) ($query->unions ?? []) as $union) {
            $nested = is_array($union) ? ($union['query'] ?? null) : null;

            if ($nested instanceof \Illuminate\Database\Eloquent\Builder) {
                $nested = $nested->getQuery();
            }

            if ($nested instanceof \Illuminate\Database\Query\Builder) {
                $this->markUncertainInQuery($nested, $tracked, $depth + 1);
            }

            if ($this->queryDependencyUncertain) {
                return;
            }
        }
    }

    /**
     * @param  array<int, mixed>  $clauses
     * @param  mixed  $query
     * @param  mixed  $tracked
     */
    protected function markUncertainInClauses(array $clauses, $query, $tracked, int $depth): void
    {
        foreach ($clauses as $clause) {
            if (! is_array($clause)) {
                continue;
            }

            if (strtolower((string) ($clause['type'] ?? '')) === 'raw'
                && is_string($clause['sql'] ?? null)
                && preg_match('/\bselect\b/i', $clause['sql'])) {
                $this->queryDependencyUncertain = true;

                return;
            }

            if ($this->containsSubqueryExpression($clause['value'] ?? null, $query)
                || $this->containsSubqueryExpression($clause['values'] ?? null, $query)) {
                $this->queryDependencyUncertain = true;

                return;
            }

            $nested = $clause['query'] ?? null;

            if (is_array($nested)) {
                $this->markUncertainInClauses($nested, $query, $tracked, $depth);
            } elseif ($nested instanceof \Illuminate\Database\Eloquent\Builder) {
                $this->markUncertainInQuery($nested->getQuery(), $tracked, $depth + 1);
            } elseif ($nested instanceof \Illuminate\Database\Query\Builder) {
                $this->markUncertainInQuery($nested, $tracked, $depth + 1);
            }

            if ($this->queryDependencyUncertain) {
                return;
            }
        }
    }

    /**
     * Whether a where/having value wraps a subquery expression, which is how
     * whereIn($column, $subquery) is compiled.
     *
     * @param  mixed  $value
     * @param  mixed  $query
     */
    protected function containsSubqueryExpression($value, $query): bool
    {
        if ($value instanceof \Illuminate\Database\Query\Expression) {
            return $this->rawSqlContainsSelect($value, $query);
        }

        if (is_array($value)) {
            foreach ($value as $item) {
                if ($this->containsSubqueryExpression($item, $query)) {
                    return true;
                }
            }
        }

        return false;
    }

    /**
     * Whether a raw SQL value contains a subquery select.
     *
     * @param  mixed  $value
     */
    protected function rawSqlContainsSelect($value, $query): bool
    {
        if ($value instanceof \Illuminate\Database\Query\Expression) {
            try {
                $value = (string) $value->getValue($query->getGrammar());
            } catch (\Throwable $e) {
                return true;
            }
        }

        return is_string($value) && (bool) preg_match('/\bselect\b/i', $value);
    }

    /**
     * Mark the query uncacheable when a column passed to get()/paginate() is a
     * raw subquery. Those columns are applied only when the query runs, so they
     * are not in the base query when the key is built.
     *
     * @param  mixed  $columns
     */
    protected function markUncertainForRawColumns($columns): void
    {
        foreach ((array) $columns as $column) {
            if ($this->rawSqlContainsSelect($column, $this->getQuery())) {
                $this->queryDependencyUncertain = true;

                return;
            }
        }
    }

    /**
     * Record the tables and models an eager-loaded relation reads.
     */
    protected function recordEagerDependency($relation): void
    {
        $this->eagerDependencyTables[] = $relation->getRelated()->getTable();
        $this->eagerDependencyModels[get_class($relation->getRelated())] = $relation->getRelated();

        if ($relation instanceof \Illuminate\Database\Eloquent\Relations\BelongsToMany) {
            $this->eagerDependencyTables[] = $relation->getTable();
        }

        if ($relation instanceof \Illuminate\Database\Eloquent\Relations\HasOneOrManyThrough) {
            $this->eagerDependencyTables[] = $relation->getParent()->getTable();
        }
    }

    /**
     * Fingerprint the complete state of a resolved relation: its underlying query
     * (SQL + bindings), any nested eager loads, and its own relation-level
     * properties (pivot columns/values, morph settings, defaults, …).
     */
    protected function relationStateFingerprint($relation, int $depth, bool $skipEagerLoads = false): string
    {
        $query = $relation->getQuery();
        $this->mergeDependencyTablesFrom($query);
        $this->markUncertainForRawSelect($query);
        $this->queryDependencyTables = array_merge(
            $this->queryDependencyTables,
            $this->collectQueryDependencyTables($query),
        );

        $parts = [
            $query->toSql(),
            $this->bindingsFingerprint($query->getBindings()),
        ];

        if (! $skipEagerLoads && count($query->getEagerLoads()) > 0) {
            $nested = $this->fingerprintEagerLoads($query, $depth + 1);
            ksort($nested);
            $parts[] = 'with:' . serialize($nested);
        }

        $props = get_mangled_object_vars($relation);

        foreach ($props as $key => $value) {
            // Protected/private props are NUL-mangled ("\0*\0query"); strip to the
            // bare name so we can skip the objects that are not relation state.
            $name = ($pos = strrpos($key, "\0")) === false ? $key : substr($key, $pos + 1);

            if (in_array($name, ['query', 'parent', 'related', 'macroBuffer'], true)) {
                continue;
            }

            // A nested builder (e.g. a one-of-many subquery on latestOfMany/ofMany)
            // cannot be serialized; its state is already reflected in the relation
            // query's SQL, so skip it rather than fail the whole resolution.
            if ($value instanceof Builder || $value instanceof \Illuminate\Database\Query\Builder) {
                continue;
            }

            $parts[] = $name . '=' . $this->valueFingerprint($value, $depth + 1);
        }

        return serialize($parts);
    }

    /**
     * Fingerprint a captured value (closure, array, object or scalar).
     *
     * @param  mixed  $value
     */
    protected function valueFingerprint($value, int $depth): string
    {
        if ($depth > 6) {
            throw new UnfingerprintableEagerLoadException('Capture nesting too deep to fingerprint.');
        }

        if (is_resource($value)) {
            throw new UnfingerprintableEagerLoadException('Capture contains a resource, which cannot be fingerprinted.');
        }

        if ($value instanceof \Closure) {
            return $this->closureFingerprint($value, $depth);
        }

        if (is_array($value)) {
            $encoded = [];

            foreach ($value as $key => $item) {
                $encoded[$key] = $this->valueFingerprint($item, $depth + 1);
            }

            return 'arr:' . serialize($encoded);
        }

        if (is_object($value)) {
            return get_class($value) . ':' . $this->objectFingerprint($value, $depth);
        }

        // serialize() keeps invalid-UTF-8 strings lossless (json substitutes every
        // bad byte with the same replacement char, collapsing distinct captures).
        if (is_string($value)) {
            return 'str:' . serialize($value);
        }

        return gettype($value) . ':' . var_export($value, true);
    }

    /**
     * Fingerprint an object by its full (including private) serialized state,
     * hashed with the configured algorithm (xxh128 by default).
     *
     * ponytail: serialize() maps a resource handle to `i:0` without throwing, so
     * two objects differing only by a held resource still collide. Don't capture
     * resource-bearing objects as eager-load constraint state.
     *
     * @param  object  $value
     */
    protected function objectFingerprint($value, int $depth): string
    {
        if ($depth > 6) {
            throw new UnfingerprintableEagerLoadException('Capture nesting too deep to fingerprint.');
        }

        try {
            return 'ser:' . $this->hashIdentifier(serialize($value));
        } catch (\Throwable $e) {
            // Unserializable state (e.g. a captured closure) cannot be fingerprinted
            // from code identity; the caller will resolve the constraint instead.
            throw new UnfingerprintableEagerLoadException('Capture contains unserializable state: ' . get_class($value), 0, $e);
        }
    }

    /**
     * Fingerprint a closure by code location, captured values and any bound
     * `$this` state, memoized per closure instance for this builder's lifetime.
     */
    protected function closureFingerprint(\Closure $closure, int $depth): string
    {
        $this->closureFingerprints ??= new \WeakMap();

        if (isset($this->closureFingerprints[$closure])) {
            return $this->closureFingerprints[$closure];
        }

        try {
            $reflection = new \ReflectionFunction($closure);

            $parts = [
                $this->normalizeFilePath((string) $reflection->getFileName()),
                (string) $reflection->getStartLine(),
                (string) $reflection->getEndLine(),
            ];

            foreach ($reflection->getStaticVariables() as $name => $variable) {
                $parts[] = $name . '=' . $this->valueFingerprint($variable, $depth + 1);
            }

            // A bound object may carry state the constraint reads ($this->...).
            // Skip Laravel's combineConstraints() wrapper and MorphTo macro
            // closures: their builder/relation state is fingerprinted separately.
            $bound = $reflection->getClosureThis();

            if ($bound !== null
                && ! $bound instanceof Builder
                && ! $bound instanceof \Illuminate\Database\Eloquent\Relations\Relation) {
                $parts[] = 'this=' . $this->objectFingerprint($bound, $depth + 1);
            }

            $fingerprint = serialize($parts);
        } catch (\Throwable $e) {
            throw new UnfingerprintableEagerLoadException('Closure could not be fingerprinted.', 0, $e);
        }

        return $this->closureFingerprints[$closure] = $fingerprint;
    }

    /**
     * Normalize a file path so cache keys stay stable across deploy directories.
     */
    protected function normalizeFilePath(string $path): string
    {
        $path = str_replace('\\', '/', $path);

        try {
            $base = str_replace('\\', '/', base_path()) . '/';

            if (str_starts_with($path, $base)) {
                return substr($path, strlen($base));
            }
        } catch (\Throwable $e) {
            // No application bound (e.g. bare PHPUnit) — use the path as-is.
        }

        return $path;
    }

    /**
     * Get the cache tags for the query.
     *
     * @return array
     */
    protected function getCacheTags()
    {
        $tags = [
            'model_cache',
            get_class($this->model),
            $this->model->getTable(),
        ];

        // A key may not have been built yet (e.g. a manual tag flush). Resolve
        // eager loads here so their tables are still recorded.
        if (! $this->eagerDependenciesResolved && count($this->eagerLoad) > 0) {
            $this->fingerprintEagerLoads($this);
            $this->eagerDependenciesResolved = true;
        }

        $tables = array_merge(
            $this->queryDependencyTables,
            $this->eagerDependencyTables,
            array_keys($this->eagerDependencyModels),
            $this->collectQueryDependencyTables($this->toBase()),
        );

        $tables = array_values(array_unique(array_filter(
            $tables,
            fn($table) => is_string($table) && $table !== '',
        )));
        sort($tables);

        foreach ($tables as $table) {
            if (! in_array($table, $tags, true)) {
                $tags[] = $table;
            }
        }

        return $tags;
    }

    /**
     * Tags that a per-model flush resets. The shared 'model_cache' tag is
     * intentionally excluded: TagSet::reset() would invalidate every model.
     *
     * @return array<int, string>
     */
    protected function getModelFlushTags(): array
    {
        return [
            get_class($this->model),
            $this->model->getTable(),
        ];
    }

    /**
     * Record the tables read by a withCount()/withSum()/… relation.
     */
    protected function recordAggregateDependencies(string $name): void
    {
        $builder = $this;

        foreach (explode('.', $name) as $segment) {
            try {
                $relation = $builder->getRelation($segment);
            } catch (\Throwable $e) {
                $this->queryDependencyUncertain = true;

                return;
            }

            if ($relation instanceof \Illuminate\Database\Eloquent\Relations\MorphTo) {
                $this->queryDependencyUncertain = true;

                return;
            }

            $this->queryDependencyTables[] = $relation->getRelated()->getTable();
            $this->eagerDependencyModels[get_class($relation->getRelated())] = $relation->getRelated();

            if ($relation instanceof \Illuminate\Database\Eloquent\Relations\BelongsToMany) {
                $this->queryDependencyTables[] = $relation->getTable();
            }

            if ($relation instanceof \Illuminate\Database\Eloquent\Relations\HasOneOrManyThrough) {
                $this->queryDependencyTables[] = $relation->getParent()->getTable();
            }

            $builder = $relation->getQuery();
        }
    }

    /**
     * Collect every table a query builder reads: from, joins, where subqueries
     * (whereHas/whereExists/whereIn(subquery)) and unions.
     *
     * @param  mixed  $query
     * @return array<int, string>
     */
    protected function collectQueryDependencyTables($query, int $depth = 0): array
    {
        if ($depth > 6 || ! is_object($query)) {
            return [];
        }

        if ($query instanceof \Illuminate\Database\Eloquent\Relations\Relation) {
            $query = $query->getQuery();
        }

        if ($query instanceof \Illuminate\Database\Eloquent\Builder) {
            $query = $query->toBase();
        }

        if (! $query instanceof \Illuminate\Database\Query\Builder) {
            return [];
        }

        $tables = [];

        $from = $this->dependencyTableName($query->from, $query);
        if ($from !== null) {
            $tables[] = $from;
        }

        foreach ((array) ($query->joins ?? []) as $join) {
            $joinTable = is_array($join)
                ? ($join['table'] ?? null)
                : ($join->table ?? null);
            $table = $this->dependencyTableName($joinTable, $query);

            if ($table !== null) {
                $tables[] = $table;
            }
        }

        foreach ((array) ($query->wheres ?? []) as $where) {
            $tables = array_merge($tables, $this->collectWhereDependencyTables($where, $depth + 1));
        }

        foreach ((array) ($query->unions ?? []) as $union) {
            $tables = array_merge(
                $tables,
                $this->collectQueryDependencyTables($union['query'] ?? null, $depth + 1),
            );
        }

        return $tables;
    }

    /**
     * @param  array<string, mixed>  $where
     * @return array<int, string>
     */
    protected function collectWhereDependencyTables(array $where, int $depth): array
    {
        if ($depth > 6) {
            return [];
        }

        if (isset($where['query'])) {
            if (is_array($where['query'])) {
                $tables = [];

                foreach ($where['query'] as $nested) {
                    if (is_array($nested)) {
                        $tables = array_merge($tables, $this->collectWhereDependencyTables($nested, $depth + 1));
                    }
                }

                return $tables;
            }

            return $this->collectQueryDependencyTables($where['query'], $depth + 1);
        }

        return [];
    }

    /**
     * Resolve a table name, or mark the query uncacheable when it cannot be
     * recovered safely (fromSub()/joinSub() store an opaque Expression).
     *
     * @param  mixed  $table
     */
    protected function dependencyTableName($table, $query): ?string
    {
        if (is_string($table)) {
            $table = trim($table);

            if ($table === '') {
                return null;
            }

            // "posts as p" / "posts p" -> "posts"
            return preg_split('/\s+/', $table)[0];
        }

        if ($table instanceof \Illuminate\Database\Query\Expression) {
            try {
                $raw = (string) $table->getValue($query->getGrammar());

                if ($raw !== '' && ! str_contains($raw, '(')) {
                    return preg_split('/\s+/', trim($raw))[0];
                }
            } catch (\Throwable $e) {
                // fall through
            }
        }

        $this->queryDependencyUncertain = true;

        return null;
    }

    /**
     * Get the models without cache.
     *
     * @param  array  $columns
     * @return Collection
     */
    protected function getWithoutCache($columns = ['*'])
    {
        return parent::get($columns);
    }

    /**
     * Get the cache driver to use.
     *
     * @return Repository
     */
    protected function getCacheDriver()
    {
        if ($this->cacheDriver !== null) {
            return $this->cacheDriver;
        }

        try {
            $cacheStore = config('model-cache.cache_store');

            if ($cacheStore) {
                $this->cacheDriver = Cache::store($cacheStore);
            } else {
                $this->cacheDriver = Cache::store();
            }
        } catch (\Throwable $e) {
            // Surface a misconfigured store instead of silently using another one,
            // then fall back so reads don't break.
            resolve(ModelCacheDebugger::class)->warning("Configured model cache store is unavailable ({$e->getMessage()}); falling back to the default cache store.");
            $this->cacheDriver = Cache::store(config('cache.default'));
        }

        return $this->cacheDriver;
    }
}
